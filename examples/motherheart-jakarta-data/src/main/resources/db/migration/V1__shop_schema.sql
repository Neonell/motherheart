-- The heart of the shop. Everything else in the application exists to protect it.
-- This file is identical in motherheart-jakarta-data and motherheart-jooq.

create table customer
(
    id    bigint generated by default as identity primary key,
    name  varchar(200) not null,
    email varchar(320) not null unique
);

create table product
(
    id    bigint generated by default as identity primary key,
    name  varchar(200)   not null,
    price numeric(12, 2) not null check (price >= 0)
);

create table purchase_order
(
    id          bigint generated by default as identity primary key,
    customer_id bigint    not null references customer (id),
    ordered_at  timestamp not null
);

create index purchase_order_customer_idx on purchase_order (customer_id);
create index purchase_order_ordered_at_idx on purchase_order (ordered_at);

create table order_line
(
    id         bigint generated by default as identity primary key,
    order_id   bigint         not null references purchase_order (id) on delete cascade,
    product_id bigint         not null references product (id),
    quantity   integer        not null check (quantity > 0),
    unit_price numeric(12, 2) not null
);

create index order_line_order_idx on order_line (order_id);
create index order_line_product_idx on order_line (product_id);
